const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'../..');
const quote=v=>"'"+String(v).replaceAll("'","''")+"'";
const names=new Intl.DisplayNames(['es'],{type:'region'});
const countries=fs.readFileSync(path.join(root,'backend/data/countryInfo.txt'),'utf8').split(/\r?\n/).filter(l=>l&&!l.startsWith('#')).map(l=>l.split('\t')).filter(c=>/^[A-Z]{2}$/.test(c[0])&&!['AN','CS'].includes(c[0])).map(c=>({code:c[0],name:names.of(c[0])||c[4]}));
const co=JSON.parse(fs.readFileSync(path.join(root,'backend/data/colombia-source.json'),'utf8'));
const title=s=>s.toLocaleLowerCase('es').split(' ').map(w=>w?w[0].toUpperCase()+w.slice(1):w).join(' ').replace('D.c.','D.C.');
const regions=[...new Map(co.map(c=>[c.cod_dpto,{code:'CO-'+c.cod_dpto,name:title(c.dpto)}])).values()];
const cities=co.map(c=>({code:'CO-'+c.cod_mpio,region_code:'CO-'+c.cod_dpto,country_code:'CO',name:title(c.nom_mpio),latitude:Number(c.latitud.replace(',','.')),longitude:Number(c.longitud.replace(',','.'))}));
const inserts=[];
inserts.push('insert into public.countries(code,name) values '+countries.map(c=>'('+quote(c.code)+','+quote(c.name)+')').join(',')+';');
inserts.push('insert into public.regions(code,country_code,name) values '+regions.map(c=>'('+quote(c.code)+",'CO',"+quote(c.name)+')').join(',')+';');
for(let i=0;i<cities.length;i+=200)inserts.push('insert into public.cities(code,region_code,country_code,name,latitude,longitude) values '+cities.slice(i,i+200).map(c=>'('+[c.code,c.region_code,c.country_code,c.name].map(quote).join(',')+','+c.latitude+','+c.longitude+')').join(',')+';');
fs.writeFileSync(path.join(root,'backend/data/location-catalog.json'),JSON.stringify({countries,regions,cities}));
const migration=path.join(root,'supabase/migrations/20261123165846_profile_catalogs_currency_media.sql');
let sql=fs.readFileSync(migration,'utf8');
if(sql.includes('-- CATALOG_DATA'))sql=sql.replace('-- CATALOG_DATA',inserts.join('\n'));
let feed=fs.readFileSync(path.join(root,'supabase/migrations/20261101151500_secure_saved_status_in_feed.sql'),'utf8');
feed=feed.slice(feed.indexOf('create or replace view'));
feed=feed.replace('as is_saved_by_me','as is_saved_by_me, e.categories');
sql=sql.replace('-- FEED_VIEW',feed);
fs.writeFileSync(migration,sql);
console.log({countries:countries.length,regions:regions.length,cities:cities.length});
